namespace Gpc.Engine.Runtime;

/// <summary>
/// The 128x64 one-bit OLED a script draws on. Drawing persists until cleared, as on the device.
/// Hosts read <see cref="Pixels"/> and repaint when <see cref="Version"/> changes. Allocation-free.
/// </summary>
public sealed class Oled
{
    public const int Width = 128, Height = 64;
    public const int TextBufferSize = 18;

    // Font cells per size. LARGE 16x26 is stated by the guide; SMALL and MEDIUM are UNVERIFIED.
    public static readonly (int w, int h, int scale, int dx, int dy)[] Fonts =
    {
        (7, 10, 1, 1, 1),   // OLED_FONT_SMALL
        (11, 18, 2, 0, 2),  // OLED_FONT_MEDIUM
        (16, 26, 3, 0, 2),  // OLED_FONT_LARGE
    };

    readonly byte[] _pixels = new byte[Width * Height];
    readonly byte[] _text = new byte[TextBufferSize + 1]; // putc_oled positions are 1-based

    /// <summary>Row-major, one byte per pixel: 1 = lit.</summary>
    public ReadOnlySpan<byte> Pixels => _pixels;

    /// <summary>Changes whenever the screen changes.</summary>
    public int Version { get; private set; }

    public bool Lit(int x, int y) => (uint)x < Width && (uint)y < Height && _pixels[y * Width + x] != 0;

    static byte Ink(int color) => color != 0 ? (byte)1 : (byte)0;

    void Set(int x, int y, byte ink)
    {
        if ((uint)x < Width && (uint)y < Height) _pixels[y * Width + x] = ink;
    }

    public void Clear(int color)
    {
        Array.Fill(_pixels, Ink(color));
        Version++;
    }

    public void Pixel(int x, int y, int color)
    {
        Set(x, y, Ink(color));
        Version++;
    }

    public void Line(int x0, int y0, int x1, int y1, int thickness, int color)
    {
        byte ink = Ink(color);
        int t = Math.Clamp(thickness, 1, 127), half = (t - 1) / 2;
        int dx = Math.Abs(x1 - x0), sx = x0 < x1 ? 1 : -1;
        int dy = -Math.Abs(y1 - y0), sy = y0 < y1 ? 1 : -1;
        int err = dx + dy;
        for (int guard = 0; guard < 512; guard++)
        {
            for (int oy = 0; oy < t; oy++)
                for (int ox = 0; ox < t; ox++)
                    Set(x0 - half + ox, y0 - half + oy, ink);
            if (x0 == x1 && y0 == y1) break;
            int e2 = 2 * err;
            if (e2 >= dy) { err += dy; x0 += sx; }
            if (e2 <= dx) { err += dx; y0 += sy; }
        }
        Version++;
    }

    public void Rect(int x, int y, int w, int h, bool fill, int color)
    {
        byte ink = Ink(color);
        w = Math.Clamp(w, 0, Width); h = Math.Clamp(h, 0, Height);
        for (int yy = y; yy < y + h; yy++)
            for (int xx = x; xx < x + w; xx++)
                if (fill || yy == y || yy == y + h - 1 || xx == x || xx == x + w - 1)
                    Set(xx, yy, ink);
        Version++;
    }

    public void Circle(int cx, int cy, int r, bool fill, int color)
    {
        byte ink = Ink(color);
        r = Math.Clamp(r, 0, 63);
        // pixel centres within half a pixel of the radius form the ring
        int r2 = r * r;
        for (int y = -r; y <= r; y++)
            for (int x = -r; x <= r; x++)
            {
                int d = x * x + y * y;
                if (d <= r2 + r && (fill || d >= r2 - r)) Set(cx + x, cy + y, ink);
            }
        Version++;
    }

    /// <summary>Draws one character; returns the cell width.</summary>
    public int Char(int x, int y, int font, int ch, int color)
    {
        var (w, _, scale, dx, dy) = Fonts[Math.Clamp(font, 0, Fonts.Length - 1)];
        int glyph = ch is >= 32 and <= 136 ? ch - 32 : '?' - 32;
        byte ink = Ink(color);
        for (int col = 0; col < 5; col++)
        {
            int bits = Font5x7[glyph * 5 + col];
            for (int row = 0; row < 7; row++)
            {
                if ((bits & (1 << row)) == 0) continue;
                for (int sy = 0; sy < scale; sy++)
                    for (int sx = 0; sx < scale; sx++)
                        Set(x + dx + col * scale + sx, y + dy + row * scale + sy, ink);
            }
        }
        Version++;
        return w;
    }

    /// <summary>Draws a zero-terminated string.</summary>
    public void Text(int x, int y, int font, int color, ReadOnlySpan<byte> s)
    {
        foreach (byte b in s)
        {
            if (b == 0) break;
            x += Char(x, y, font, b, color);
        }
    }

    public void PutChar(int position, int ch)
    {
        if (position is >= 1 and <= TextBufferSize) _text[position] = (byte)ch;
    }

    /// <summary>puts_oled: draws text-buffer characters 1..length.</summary>
    public void PutBuffer(int x, int y, int font, int length, int color)
    {
        length = Math.Clamp(length, 0, TextBufferSize);
        for (int i = 1; i <= length; i++) x += Char(x, y, font, _text[i] == 0 ? ' ' : _text[i], color);
    }

    /// <summary>image_oled: data is width, height, then packed pixels left to right, top to bottom, MSB first (UNVERIFIED bit order).</summary>
    public void Image(int x, int y, int color, bool clearBackground, ReadOnlySpan<byte> data)
    {
        if (data.Length < 2) return;
        int w = data[0], h = data[1];
        byte ink = Ink(color), bg = Ink(color == 0 ? 1 : 0);
        for (int i = 0; i < w * h; i++)
        {
            int byteIndex = 2 + i / 8;
            if (byteIndex >= data.Length) break;
            bool on = (data[byteIndex] & (0x80 >> (i % 8))) != 0;
            if (on) Set(x + i % w, y + i / w, ink);
            else if (clearBackground) Set(x + i % w, y + i / w, bg);
        }
        Version++;
    }

